import type { Locator, Page } from '@playwright/test';

import { expect, resetStub, test } from './fixtures';

/**
 * The library upload flow, and PART-scoped access cards.
 *
 * The upload tests drive a real file through a real cross-origin PUT to the
 * storage stand-in — preflight included — because that is the part of the flow
 * the product actually has. Mocking the PUT would leave the one step most
 * likely to break untested.
 */

const STUB_API = `http://127.0.0.1:${process.env.STUB_API_PORT ?? 4599}`;

test.beforeEach(async ({ page }) => {
  await resetStub(page);
});

/** A small, genuinely valid PDF, so nothing depends on the bytes. */
const PDF = {
  name: 'revision-paper.pdf',
  mimeType: 'application/pdf',
  buffer: Buffer.from('%PDF-1.4\n1 0 obj\n<<>>\nendobj\ntrailer\n<<>>\n%%EOF\n'),
};

/**
 * The English title, not the Arabic one.
 *
 * `getByLabel('Title')` matches on a substring, so it finds both `Title
 * (required)` and `Title (Arabic)` and Playwright refuses the ambiguity. The
 * accessible name carries the screen-reader-only "(required)" the `Field`
 * appends, which is what makes the two distinguishable.
 */
function fillTitle(dialog: Locator, value: string) {
  return dialog.getByRole('textbox', { name: 'Title (required)' }).fill(value);
}

async function openAddDocument(page: Page) {
  await page.goto('/library/mat-1');
  await page.getByRole('button', { name: 'Add document' }).first().click();
  return page.getByRole('dialog');
}

// ---------------------------------------------------------------------------
// Library upload
// ---------------------------------------------------------------------------

test.describe('library upload', () => {
  test('uploads a chosen file and reports it as uploaded', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openAddDocument(page);

    await dialog.locator('input[type="file"]').setInputFiles(PDF);

    await expect(dialog.getByText('Uploaded')).toBeVisible();
    await expect(dialog.getByText(PDF.name)).toBeVisible();
  });

  test('offers no place to type a storage key', async ({ page, signIn }) => {
    // The manual key was never something an administrator could get right:
    // the key is generated by the server and only appears in a response.
    await signIn('admin');
    const dialog = await openAddDocument(page);

    await expect(dialog.getByLabel(/object key/i)).toHaveCount(0);
    await expect(dialog.getByPlaceholder(/library\//)).toHaveCount(0);
  });

  test('refuses to save a new document before a file is uploaded', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openAddDocument(page);

    await fillTitle(dialog, 'Paper 3');
    await dialog.getByLabel('Price').fill('75');

    // No file yet, so the part would point at nothing.
    await expect(dialog.getByRole('button', { name: 'Add document' })).toBeDisabled();
  });

  test('creates the document with the key the server issued', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openAddDocument(page);

    await fillTitle(dialog, 'Paper 3');
    await dialog.getByLabel('Price').fill('75');
    await dialog.locator('input[type="file"]').setInputFiles(PDF);
    await expect(dialog.getByText('Uploaded')).toBeVisible();

    await Promise.all([
      page.waitForResponse(
        (r) =>
          r.url().includes('/api/proxy/admin/library/materials/') &&
          r.request().method() === 'POST',
      ),
      dialog.getByRole('button', { name: 'Add document' }).click(),
    ]);

    // Asserted on the request, not on the screen: the claim is that the
    // dashboard sent the server's key, and a rendered string cannot show that.
    const sent = await (
      await page.request.get(`${STUB_API}/api/v1/__test__/last-library-part`)
    ).json();

    expect(sent.data.objectKey).toBe('library/stub-object.pdf');
    expect(sent.data.title).toBe('Paper 3');
    expect(sent.data.price).toBe(75);
  });

  test('reports a failed upload and does not pretend it worked', async ({ page, signIn }) => {
    await signIn('admin');
    await page.request.get(`${STUB_API}/api/v1/__test__/fail-upload`);

    const dialog = await openAddDocument(page);
    await dialog.locator('input[type="file"]').setInputFiles(PDF);

    await expect(dialog.getByRole('alert')).toContainText(/storage refused|could not reach/i);
    await expect(dialog.getByText('Uploaded')).toHaveCount(0);
  });

  test('rejects a file type the server would refuse, without a round trip', async ({
    page,
    signIn,
  }) => {
    await signIn('admin');
    const dialog = await openAddDocument(page);

    await dialog.locator('input[type="file"]').setInputFiles({
      name: 'notes.txt',
      mimeType: 'text/plain',
      buffer: Buffer.from('hello'),
    });

    await expect(dialog.getByRole('alert')).toContainText(/file type is not accepted/i);
  });

  test('never exposes a permanent or public storage URL', async ({ page, signIn }) => {
    // The bucket is private. The upload URL is a short-lived write-only
    // signature, and it must not survive into anything the page renders.
    await signIn('admin');
    const dialog = await openAddDocument(page);

    await dialog.locator('input[type="file"]').setInputFiles(PDF);
    await expect(dialog.getByText('Uploaded')).toBeVisible();

    const text = (await dialog.textContent()) ?? '';
    expect(text).not.toContain('__storage__');
    expect(text).not.toContain('http://');
    expect(text).not.toContain('https://');
    expect(text).not.toContain('library/stub-object');

    await expect(dialog.getByRole('link')).toHaveCount(0);
  });

  test('the presign endpoint is refused to a teacher', async ({ page, signIn }) => {
    // @AdminOnly() on the real controller — there is no teacher-scoped
    // library route anywhere.
    await signIn('teacher');

    const response = await page.request.post('/api/proxy/storage/uploads/library-document', {
      headers: { 'x-dashboard-request': '1', origin: new URL(page.url()).origin },
      data: { filename: 'a.pdf', contentType: 'application/pdf', sizeBytes: 10 },
    });

    expect(response.status(), await response.text()).toBe(403);
  });
});

