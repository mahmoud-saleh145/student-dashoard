async function openGenerate(page: Page) {
  await page.goto('/codes');
  await page
    .getByRole('button', { name: /generate codes/i })
    .first()
    .click();
  return page.getByRole('dialog');
}

test.describe('PART access cards', () => {
  test('offers PART as a target alongside the existing three', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openGenerate(page);

    const target = dialog.getByLabel('What do these cards unlock?');
    await expect(target.locator('option')).toHaveText([
      'A whole course',
      'One part of a course',
      'One section of a course',
      'Everything by one teacher',
    ]);
  });

  test('loads the parts of the chosen course', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openGenerate(page);

    await dialog.getByLabel('What do these cards unlock?').selectOption('PART');
    await dialog.getByLabel('Course').selectOption('course-1');

    // Part 1 has a section; Part 2 has none, so a card for it would unlock
    // nothing and the server refuses it. It is not offered.
    await expect(dialog.getByLabel('Part').locator('option')).toContainText([
      'Part 1 - Before mid',
    ]);
    await expect(dialog.getByLabel('Part')).not.toContainText('Part 2 - After mid');
  });

  test('will not generate until a part is chosen', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openGenerate(page);

    await dialog.getByLabel('What do these cards unlock?').selectOption('PART');
    await dialog.getByLabel('Course').selectOption('course-1');

    await expect(dialog.getByRole('button', { name: /generate/i })).toBeDisabled();
  });

  test('sends coursePartId when generating a PART card', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openGenerate(page);

    await dialog.getByLabel('What do these cards unlock?').selectOption('PART');
    await dialog.getByLabel('Course').selectOption('course-1');
    await dialog.getByLabel('Part').selectOption('part-1');
    await dialog.getByLabel('How many cards').fill('10');
    // Wait for the request to land before asking the stub what it received —
    // reading straight after the click raced the browser and flaked.
    await Promise.all([
      page.waitForResponse((r) => r.url().includes('/api/proxy/admin/codes/generate')),
      dialog.getByRole('button', { name: /generate/i }).click(),
    ]);

    const sent = await (
      await page.request.get(`${STUB_API}/api/v1/__test__/last-generate-codes`)
    ).json();

    expect(sent.data.targetType).toBe('PART');
    expect(sent.data.coursePartId).toBe('part-1');
    expect(sent.data.courseId).toBe('course-1');
    expect(sent.data.count).toBe(10);
  });

  test('still generates a whole-course card the old way', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openGenerate(page);

    await dialog.getByLabel('Course').selectOption('course-1');
    await dialog.getByLabel('How many cards').fill('5');
    // Wait for the request to land before asking the stub what it received —
    // reading straight after the click raced the browser and flaked.
    await Promise.all([
      page.waitForResponse((r) => r.url().includes('/api/proxy/admin/codes/generate')),
      dialog.getByRole('button', { name: /generate/i }).click(),
    ]);

    const sent = await (
      await page.request.get(`${STUB_API}/api/v1/__test__/last-generate-codes`)
    ).json();

    expect(sent.data.targetType).toBe('COURSE');
    expect(sent.data.courseId).toBe('course-1');
    // The part must not leak into a target that has nothing to do with it.
    expect(sent.data.coursePartId).toBeUndefined();
  });

  test('still generates a section card', async ({ page, signIn }) => {
    await signIn('admin');
    const dialog = await openGenerate(page);

    await dialog.getByLabel('What do these cards unlock?').selectOption('SECTION');
    await dialog.getByLabel('Course').selectOption('course-1');
    await dialog.getByLabel('Section').selectOption('sec-1');
    // Wait for the request to land before asking the stub what it received —
    // reading straight after the click raced the browser and flaked.
    await Promise.all([
      page.waitForResponse((r) => r.url().includes('/api/proxy/admin/codes/generate')),
      dialog.getByRole('button', { name: /generate/i }).click(),
    ]);

    const sent = await (
      await page.request.get(`${STUB_API}/api/v1/__test__/last-generate-codes`)
    ).json();

    expect(sent.data.targetType).toBe('SECTION');
    expect(sent.data.sectionId).toBe('sec-1');
    expect(sent.data.coursePartId).toBeUndefined();
  });

  test('shows PART as a readable label rather than a raw enum', async ({ page, signIn }) => {
    await signIn('admin');
    await page.goto('/codes');

    await expect(page.getByLabel('Target type').locator('option')).toContainText([
      'Course part',
    ]);
  });

  test('code generation stays refused to a teacher', async ({ page, signIn }) => {
    // Every admin code route is @AdminOnly(); adding PART changed none of that.
    await signIn('teacher');

    const response = await page.request.post('/api/proxy/admin/codes/generate', {
      headers: { 'x-dashboard-request': '1', origin: new URL(page.url()).origin },
      data: { targetType: 'PART', courseId: 'course-1', coursePartId: 'part-1', count: 1 },
    });

    expect(response.status(), await response.text()).toBe(403);
  });
});
